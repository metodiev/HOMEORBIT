const dictionaries: Record<Locale, Record<string, string>> = { en, bg };

export function normalizeLocale(value: string | null | undefined): Locale {
  return value === "bg" ? "bg" : "en";
}

export function t(locale: string | null | undefined, key: string): string {
  const dictionary = dictionaries[normalizeLocale(locale)];
  return dictionary[key] ?? en[key] ?? key;
}

export function intlLocale(locale: string | null | undefined): string {
  return normalizeLocale(locale) === "bg" ? "bg-BG" : "en-GB";
}
